      'low' => 'Low Risk',
      'medium' => 'Medium Risk',
      'high' => 'High Risk',
      'critical' => 'Critical Risk',
    ];

    return $labels[$riskLevel] ?? ucfirst($riskLevel ?? 'Unknown');
  }

