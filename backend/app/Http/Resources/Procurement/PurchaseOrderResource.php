  /**
   * Format a date field safely
   */
  private function formatDate($value): ?string
  {
    if (!$value) {
      return null;
    }

    try {
      if (is_string($value)) {
        $timestamp = strtotime($value);
        if ($timestamp !== false) {
          return date('Y-m-d', $timestamp);
        }
        return $value;
      }

      if ($value instanceof \Carbon\Carbon) {
        return $value->toDateString();
      }

      if ($value instanceof \DateTime) {
        return $value->format('Y-m-d');
      }

      return null;
    } catch (\Exception $e) {
      Log::warning('[PurchaseOrderResource] Failed to format date', [
        'value' => $value,
        'error' => $e->getMessage(),
      ]);
      return null;
    }
  }

  /**
   * Format a datetime field safely
   */
  private function formatDateTime($value): ?string
  {
    if (!$value) {
      return null;
    }

    try {
      if (is_string($value)) {
        $timestamp = strtotime($value);
        if ($timestamp !== false) {
          return date('Y-m-d H:i:s', $timestamp);
        }
        return $value;
      }

      if ($value instanceof \Carbon\Carbon) {
        return $value->toDateTimeString();
      }

      if ($value instanceof \DateTime) {
        return $value->format('Y-m-d H:i:s');
      }

      return null;
    } catch (\Exception $e) {
      Log::warning('[PurchaseOrderResource] Failed to format datetime', [
        'value' => $value,
        'error' => $e->getMessage(),
      ]);
      return null;
    }
  }

  /**
   * Format upload data from the Upload model
   */
  private function formatUploadData($upload): ?array
  {
    if (!$upload) {
      return null;
    }

    $uploadedByUser = null;
    $uploadedByName = null;

    if ($upload->relationLoaded('uploadedBy') && $upload->uploadedBy) {
      $user = $upload->uploadedBy;
      $uploadedByUser = [
        'id' => $user->id,
        'full_name' => $user->full_name,
        'first_name' => $user->first_name,
        'last_name' => $user->last_name,
        'email' => $user->email,
        'role_label' => $user->role_label,
      ];
      $uploadedByName = $user->full_name;
    } elseif (!empty($upload->uploaded_by)) {
      try {
        $user = \App\Models\User::find($upload->uploaded_by);
        if ($user) {
          $uploadedByUser = [
            'id' => $user->id,
            'full_name' => $user->full_name,
            'first_name' => $user->first_name,
            'last_name' => $user->last_name,
            'email' => $user->email,
            'role_label' => $user->role_label,
          ];
          $uploadedByName = $user->full_name;
        } else {
          $uploadedByName = 'Unknown User (ID: ' . $upload->uploaded_by . ')';
        }
      } catch (\Exception $e) {
        $uploadedByName = 'Unknown User';
      }
    }

    return [
      'id' => $upload->id,
      'uploadable_type' => $upload->uploadable_type,
      'uploadable_id' => $upload->uploadable_id,
      'file_name' => $upload->file_name,
      'original_name' => $upload->original_name,
      'file_path' => $upload->file_path,
      'file_url' => $upload->file_url ?? $upload->url,
      'file_type' => $upload->file_type,
      'mime_type' => $upload->mime_type,
      'extension' => $upload->extension,
      'file_size' => $upload->file_size,
      'formatted_size' => $upload->formatted_size,
      'width' => $upload->width,
      'height' => $upload->height,
      'image_orientation' => $upload->image_orientation,
      'is_image' => $upload->is_image,
      'is_document' => $upload->file_type === 'document',
      'disk' => $upload->disk,
      'collection' => $upload->collection,
      'title' => $upload->title,
      'description' => $upload->description,
      'meta_data' => $upload->meta_data,
      'status' => $upload->status,
      'status_label' => $this->getUploadStatusLabel($upload->status),
      'uploaded_by' => $upload->uploaded_by,
      'uploaded_by_user' => $uploadedByUser,
      'uploaded_by_name' => $uploadedByName,
      'uploaded_at' => $this->formatDateTime($upload->uploaded_at),
      'created_at' => $this->formatDateTime($upload->created_at),
      'updated_at' => $this->formatDateTime($upload->updated_at),
    ];
  }

  /**
   * Get upload status label
   */
  private function getUploadStatusLabel(?string $status): string
  {
    $labels = [
      'completed' => 'Completed',
      'pending' => 'Pending',
      'processing' => 'Processing',
      'failed' => 'Failed',
      'deleted' => 'Deleted',
    ];

    return $labels[$status] ?? ucfirst($status ?? 'Unknown');
  }

